#!/usr/bin/env python3
"""Generate the weekly odds-capture schedule from the season's real kickoffs.

The Odds API stops serving a game's markets the moment it kicks off, so a
closing price has to be taken before that game starts — not before *most* games
start. A single Sunday-noon capture misses every game that kicks off earlier,
and in 2026 that is 33 of 272: all 19 Thursday games, 4 Friday, 2 Saturday, 2
Wednesday, and the 09:30 London kickoffs. Those prices are unbuyable afterwards
at any cost, which makes this a data-loss bug rather than a tidiness one.

Kickoff waves move season to season — Wednesday openers, Black Friday, Christmas
on a Friday, flexed Sunday windows — so the times are derived here rather than
written down. Re-run after `make ingest` refreshes the schedule:

    python scripts/25_odds_schedule.py            # show the derived schedule
    python scripts/25_odds_schedule.py --write    # write the launchd plists
    python scripts/25_odds_schedule.py --write --load    # and (re)load them

Generosity is cheap because `weekly_odds.sh` refuses to call the API when no
kickoff is near, so a slot that a flex move emptied costs nothing. See
`odds_capture` in config/settings.yaml.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import polars as pl  # noqa: E402

from src.utils.config import get_config  # noqa: E402
from src.utils.paths import get_path  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
AGENTS = Path.home() / "Library" / "LaunchAgents"
LABELS = {"open": "com.mthompson.nfl-odds-open",
          "close": "com.mthompson.nfl-odds-close"}

#: launchd's Weekday integers. 0 and 7 both mean Sunday; it accepts 0.
WEEKDAYS = {"Sunday": 0, "Monday": 1, "Tuesday": 2, "Wednesday": 3,
            "Thursday": 4, "Friday": 5, "Saturday": 6}


def _minutes(hhmm: str) -> int:
    h, m = hhmm.split(":")[:2]
    return int(h) * 60 + int(m)


def _hhmm(total: int) -> str:
    return f"{total // 60:02d}:{total % 60:02d}"


def kickoff_waves(season: int | None = None) -> dict[str, list[str]]:
    """Capture times per weekday, one per cluster of kickoffs.

    Each wave sits `lead_minutes` before the earliest kickoff it covers, so no
    game in a merged cluster is ever captured after it has started. Merging is
    what keeps the credit cost proportional to the number of *waves* rather than
    the number of distinct kickoff times.
    """
    cfg = get_config().get("odds_capture", {})
    lead = int(cfg.get("lead_minutes", 30))
    merge = int(cfg.get("merge_minutes", 45))

    schedule = pl.read_parquet(get_path("raw") / "schedules.parquet")
    season = season or int(schedule["season"].max())
    games = schedule.filter(pl.col("season") == season)
    if games.height == 0:
        raise SystemExit(f"no games for season {season}")
    if "weekday" not in games.columns or "gametime" not in games.columns:
        raise SystemExit("schedules.parquet has no weekday/gametime columns")

    games = games.filter(pl.col("gametime").is_not_null()
                         & pl.col("weekday").is_not_null())

    waves: dict[str, list[str]] = {}
    for weekday in games["weekday"].unique().to_list():
        times = sorted({_minutes(t) for t in
                        games.filter(pl.col("weekday") == weekday)["gametime"]})
        kept: list[int] = []
        for t in times:
            # A kickoff already covered by the last wave needs no wave of its
            # own: that wave is earlier, so it still lands before this game.
            if kept and t - kept[-1] < merge:
                continue
            kept.append(t)
        slots = [k - lead for k in kept if k - lead >= 0]
        if slots:
            waves[weekday] = [_hhmm(s) for s in slots]
    return dict(sorted(waves.items(), key=lambda kv: WEEKDAYS[kv[0]]))


def plist(label: str, snapshot: str, slots: list[tuple[str, str]]) -> str:
    """A launchd agent firing `weekly_odds.sh <snapshot>` at each slot."""
    intervals = "\n".join(
        f"    <dict><key>Weekday</key><integer>{WEEKDAYS[day]}</integer>"
        f"<key>Hour</key><integer>{_minutes(t) // 60}</integer>"
        f"<key>Minute</key><integer>{_minutes(t) % 60}</integer></dict>"
        for day, t in slots
    )
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>{label}</string>
  <key>ProgramArguments</key>
  <array>
    <string>{REPO}/scripts/weekly_odds.sh</string>
    <string>{snapshot}</string>
  </array>
  <key>WorkingDirectory</key>
  <string>{REPO}</string>
  <!-- Generated by scripts/25_odds_schedule.py from the season's kickoffs.
       Edit that, not this: a hand-edited slot is silently wrong the first time
       the league flexes a game. Slots are deliberately generous; weekly_odds.sh
       exits without spending an API credit when no kickoff is near. -->
  <key>StartCalendarInterval</key>
  <array>
{intervals}
  </array>
  <!-- If the Mac is asleep at the scheduled time, launchd runs the job as soon
       as it wakes. cron would simply skip it, and a skipped capture is a price
       that cannot be bought back. -->
  <key>StandardOutPath</key>
  <string>{REPO}/logs/launchd_{snapshot}.out</string>
  <key>StandardErrorPath</key>
  <string>{REPO}/logs/launchd_{snapshot}.err</string>
</dict>
</plist>
"""


def open_slots(cfg: dict | None = None) -> list[tuple[str, str]]:
    """The weekly opening captures, earliest first.

    More than one, because the open is what closing-line value is measured
    against and the earliest capture is the one that counts —
    `clv.line_movement` keeps the first `captured_at` per player-game. A single
    Wednesday-noon slot made "the open" a price taken 32 hours before
    Thursday's kickoff, days after the book first posted it, so every CLV
    figure was measured from a line that had already moved.

    Tuesday is as early as this can safely go, and the reason is not about
    books. `weekly_odds.sh` derives the week from the nearest kickoff ahead
    *by date*, so every hour of Monday resolves to the week that is ending —
    Monday 23:30, after Monday night's game has finished, still returns the old
    week. A Monday slot would file next week's opening prices under this week's
    number, which costs both weeks rather than one.
    """
    cfg = get_config().get("odds_capture", {}) if cfg is None else cfg
    slots = cfg.get("open_slots")
    if not slots:
        # Pre-`open_slots` config, kept so an old settings.yaml still generates.
        return [(str(cfg.get("open_weekday", "Wednesday")),
                 str(cfg.get("open_time", "12:00")))]
    pairs = [(str(sl["weekday"]), str(sl["time"])) for sl in slots]
    return sorted(pairs, key=lambda pr: (WEEKDAYS[pr[0]], _minutes(pr[1])))


def build(season: int | None = None) -> dict[str, list[tuple[str, str]]]:
    """The slots for each snapshot kind, as (weekday, HH:MM) pairs."""
    cfg = get_config().get("odds_capture", {})
    waves = kickoff_waves(season)
    close = [(day, t) for day, times in waves.items() for t in times]
    return {"open": open_slots(cfg), "close": close}


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--season", type=int, default=None)
    ap.add_argument("--write", action="store_true",
                    help="write the plists to ~/Library/LaunchAgents")
    ap.add_argument("--load", action="store_true",
                    help="bootout and re-bootstrap the agents after writing")
    a = ap.parse_args()

    slots = build(a.season)
    waves = kickoff_waves(a.season)

    print("Closing captures, derived from kickoffs:")
    for day, times in waves.items():
        print(f"  {day:10s} {'  '.join(times)}")
    print("\nOpening captures:")
    for day, t in slots["open"]:
        print(f"  {day:10s} {t}")
    print(f"\n{len(slots['close'])} close slots + {len(slots['open'])} open "
          "slots per week. Slots with no kickoff in range exit before calling "
          "the API.")

    if not a.write:
        print("\nDry run. Re-run with --write to install, --write --load to "
              "install and activate.")
        return 0

    AGENTS.mkdir(parents=True, exist_ok=True)
    for snapshot, label in LABELS.items():
        path = AGENTS / f"{label}.plist"
        path.write_text(plist(label, snapshot, slots[snapshot]))
        print(f"wrote {path}")

    if not a.load:
        print("\nNot activated. `make odds-schedule-on` to load them.")
        return 0

    uid = subprocess.run(["id", "-u"], capture_output=True, text=True).stdout.strip()
    for label in LABELS.values():
        subprocess.run(["launchctl", "bootout", f"gui/{uid}/{label}"],
                       capture_output=True)
        subprocess.run(["launchctl", "enable", f"gui/{uid}/{label}"],
                       capture_output=True)
        r = subprocess.run(
            ["launchctl", "bootstrap", f"gui/{uid}",
             str(AGENTS / f"{label}.plist")], capture_output=True, text=True)
        state = "loaded" if r.returncode == 0 else f"FAILED: {r.stderr.strip()}"
        print(f"{label}: {state}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
