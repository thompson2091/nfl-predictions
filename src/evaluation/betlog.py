"""Bets you actually placed, scored against the closing price.

Every other measurement here is a replay: what the rule *would* have returned
at prices nobody had to get filled at. This is the other kind of evidence, and
it is the one that generalises — the price you took against the price the
market closed at, on the bets you took, at the books that would have you.

**Why closing-line value and not profit.** Profit on a handful of weeks of
touchdown props is almost all variance: a 20% hit rate at +450 needs hundreds
of bets before the mean stops moving. Beating the close is measurable in
dozens, because it does not wait for a result — it asks whether the market
moved toward your number after you took it. Every serious operation in this
business is judged on it, and it is the only figure here that will tell you
whether an edge exists before the bankroll does.

**The sign convention.** `clv_pp` is your price against the closing price in
probability points, positive when you got the better of it: you paid for a
`taken_prob` chance and the market closed at `close_prob`, so a close above
what you paid means the number moved your way. A season averaging positive
`clv_pp` is the claim worth making; a season averaging negative means the
market disagreed with every pick after you made it, whatever the results said.

**A lay is scored the other way up**, which is why `side` exists. Backing a
player you want the close shorter than what you took; laying him on an exchange
you want the Yes price to drift, because that is the market agreeing he was
overrated. The archive only ever holds the Yes side, so this is a sign flip
rather than a second lookup — and without it the fade rule's best weeks would
be reported as its worst.

The log itself is a CSV you append to — `data/bets_placed.csv` — because a bet
is a thing that happens away from this machine and typing eight fields is not
the friction that stops anybody. `record` writes a row, `score` reads them all
back and joins the archive.
"""
from __future__ import annotations

from pathlib import Path

import polars as pl

from src.utils.paths import records_dir

#: Where the log lives. Deliberately outside `output/`: everything there is
#: regenerated by a make target, and this is the one file in the project that
#: cannot be rebuilt from anything. `records_dir` is what makes it movable, so
#: the rehearsal can drive this module for real without writing to it.
LOG_PATH = records_dir() / "bets_placed.csv"

#: What a row has to carry. `odds` is American, as taken; `book` is who filled
#: it, because line shopping is the one edge here that is not in doubt and a
#: log that cannot say where the price came from cannot measure it.
COLUMNS = ("placed_on", "season", "week", "market", "player", "book",
           "side", "odds", "stake", "note")

SCHEMA = {"placed_on": pl.Utf8, "season": pl.Int64, "week": pl.Int64,
          "market": pl.Utf8, "player": pl.Utf8, "book": pl.Utf8,
          "side": pl.Utf8, "odds": pl.Float64, "stake": pl.Float64,
          "note": pl.Utf8}

#: Which way a bet wants the market to move. Backing a player, you want the
#: closing price shorter than the one you took; laying him on an exchange, you
#: want it to drift, because that is the market agreeing he was overrated. One
#: sign for both would report a lay's best weeks as its worst.
SIDES = {"yes": 1.0, "no": -1.0}


def _implied(odds) -> float | None:
    """American odds to implied probability, margin included.

    Included on purpose: both ends of the comparison carry it, so it cancels,
    and de-vigging one end against a slate the other end never saw would put a
    modelling choice inside a measurement whose whole value is that it has none.
    """
    if odds is None:
        return None
    o = float(odds)
    if o == 0:
        return None
    return (100.0 / (o + 100.0)) if o > 0 else (abs(o) / (abs(o) + 100.0))


def load(path: Path | str = LOG_PATH) -> pl.DataFrame:
    """Every bet recorded, or an empty frame with the right columns."""
    p = Path(path)
    if not p.exists():
        return pl.DataFrame(schema=SCHEMA)
    df = pl.read_csv(p, schema_overrides=SCHEMA)
    missing = [c for c in COLUMNS if c not in df.columns]
    if missing:
        raise ValueError(f"{p} is missing {missing}")
    return df


def record(row: dict, path: Path | str = LOG_PATH) -> pl.DataFrame:
    """Append one bet. Returns the whole log.

    Appends rather than rewrites, and never deduplicates: two bets on the same
    player at different books is a normal thing to have done, and a log that
    silently merges them understates the stake.
    """
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    missing = [c for c in ("season", "week", "market", "player", "odds", "stake")
               if row.get(c) in (None, "")]
    if missing:
        raise ValueError(f"a bet needs {missing}")
    side = (row.get("side") or "yes").lower()
    if side not in SIDES:
        raise ValueError(f"side must be one of {sorted(SIDES)}, got {side!r}")
    row = {**row, "side": side}
    new = pl.DataFrame([{c: row.get(c) for c in COLUMNS}], schema=SCHEMA)
    out = pl.concat([load(p), new], how="vertical")
    out.write_csv(p)
    return out


def _closes(market: str) -> pl.DataFrame | None:
    """The last closing price archived for each player-week on one market."""
    from src.ingest.odds_history import HISTORY_PATH

    if not Path(HISTORY_PATH).exists():
        return None
    hist = pl.read_parquet(HISTORY_PATH)
    need = {"snapshot", "market", "season", "week", "player_name_norm", "odds"}
    if not need <= set(hist.columns):
        return None
    df = hist.filter((pl.col("snapshot") == "close")
                     & (pl.col("market") == market))
    if df.height == 0:
        return None
    sort_key = "captured_at" if "captured_at" in df.columns else "week"
    return (df.sort(sort_key)
            .unique(subset=["season", "week", "player_name_norm"], keep="last")
            .select(["season", "week", "player_name_norm",
                     pl.col("odds").alias("close_odds")]))


def score(bets: pl.DataFrame | None = None, path: Path | str = LOG_PATH) -> dict:
    """Join every logged bet to the price its market closed at.

    Unmatched bets are reported rather than dropped: a bet on a player the
    archive never captured is a hole in the capture, and hiding it would let
    the average quietly describe whichever bets happened to be joinable.
    """
    df = load(path) if bets is None else bets
    if df.height == 0:
        return {"n": 0, "rows": [], "unmatched": 0, "note": "No bets logged yet."}
    if "side" not in df.columns:
        df = df.with_columns(pl.lit("yes").alias("side"))

    from src.prediction.predict import _norm_name_expr

    df = df.with_columns(_norm_name_expr("player").alias("player_name_norm"))
    out, unmatched = [], 0
    for market in df["market"].unique().to_list():
        part = df.filter(pl.col("market") == market)
        closes = _closes(market)
        if closes is None:
            unmatched += part.height
            continue
        j = part.join(closes, on=["season", "week", "player_name_norm"],
                      how="left")
        for r in j.iter_rows(named=True):
            taken, close = _implied(r["odds"]), _implied(r.get("close_odds"))
            if close is None:
                unmatched += 1
            sign = SIDES.get((r.get("side") or "yes").lower(), 1.0)
            out.append({
                "placed_on": r.get("placed_on"), "season": r["season"],
                "week": r["week"], "market": market, "player": r["player"],
                "book": r.get("book"), "side": r.get("side") or "yes",
                "odds": r["odds"], "stake": r["stake"],
                "close_odds": r.get("close_odds"),
                "taken_prob": taken, "close_prob": close,
                "clv_pp": (None if (taken is None or close is None)
                           else (close - taken) * 100 * sign),
            })

    scored = [r for r in out if r["clv_pp"] is not None]
    beat = [r for r in scored if r["clv_pp"] > 0]
    staked = float(sum(r["stake"] or 0 for r in out))
    return {
        "n": len(out), "scored": len(scored), "unmatched": unmatched,
        "staked": staked,
        "mean_clv_pp": (sum(r["clv_pp"] for r in scored) / len(scored)
                        if scored else None),
        "beat_close_pct": (len(beat) / len(scored)) if scored else None,
        "rows": sorted(out, key=lambda r: (r["season"], r["week"],
                                           r["player"] or "")),
        "note": (None if scored else
                 "No logged bet matches an archived closing price yet."),
    }
