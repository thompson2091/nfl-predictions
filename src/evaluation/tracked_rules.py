"""Rules we are watching but have not earned the right to bet.

The measurements in this project answer questions about the past. This answers
the only question left: something looked promising in a slice of three
seasons — does it hold up going forward, on weeks nobody has seen yet.

**Why a rule has to be frozen to be tested.** The pocket below was found by
searching 21 price-by-edge cells and keeping the best. A permutation control
that shuffles which player we liked within each week reproduces a slice that
good 3% of the time, so the search is not the whole explanation — but picking
the cell on earlier seasons and grading it on the next went -7.2% in 2024 and
+8.3% in 2025, which is one good season and one bad one with intervals a mile
wide. A rule that keeps being re-tuned can never fail that way, because every
failure is absorbed into the next tuning. So the definition is written down
here, in numbers, and does not move.

**What "tracked" means and does not mean.** Picks are recorded every week with
the price available at the time. Nothing here is a recommendation, nothing
feeds the shortlist's own rows, and no figure produced by this module is
evidence of anything until it has run forward for a season. `status` says so on
every rule, and both surfaces print it.

**What will settle it, and when.** Closing-line value, not profit. Beating the
close is readable in dozens of picks, while a 20% hit rate at +450 needs
hundreds before the mean stops moving — so a rule that is real shows up here
weeks before a bankroll could tell you, and a rule that is not stops wasting
your Sundays sooner.

**A lay is scored the other way up.** Backing a player, you want the market to
come toward you: the closing price shorter than the one you took. Laying him,
you want the opposite — the Yes price *drifting*, because that is the market
agreeing he was overrated. Scoring both with one sign would have reported the
fade rule's best weeks as its worst, so `score` reads each rule's `kind` and
flips accordingly. The archive only ever holds the Yes side, which is why this
is a sign convention rather than a second lookup.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

import polars as pl

from src.utils.paths import records_dir

#: Where weekly picks accumulate. Outside `output/` for the same reason the bet
#: log is: everything in there is regenerated by a make target, and this is a
#: record of what a rule said at a moment that cannot be rebuilt afterwards —
#: re-deriving it later would quietly use today's model on last week's board.
PICKS_PATH = records_dir() / "tracked_picks.csv"

COLUMNS = ("recorded_on", "season", "week", "market", "rule", "player",
           "team", "game", "odds", "ours", "book", "edge_pp")

