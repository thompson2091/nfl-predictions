def _lay_picks(board: pl.DataFrame, rule: dict) -> list[dict]:
    """Players to lay: inside the band, and rated well under the price.

    A ratio rather than a points gap, because three points under a 30% player
    and three under a 6% one are not the same disagreement — and this band is
    all small numbers.
    """
    lo, hi = rule["min_book_pct"] / 100.0, rule["max_book_pct"] / 100.0
    sel = board.filter(
        (pl.col("market_prob") >= lo) & (pl.col("market_prob") <= hi)
        & (pl.col("prob_bet") <= pl.col("market_prob") * float(rule["max_ratio"]))
    )
    out = []
    for r in sel.sort("model_edge_pp").iter_rows(named=True):
        out.append({
            "rule": rule["name"], "player": r.get("player_name"),
            "team": r.get("team"), "game": r.get("game_label"),
            "odds": int(r["odds"]), "ours": float(r["prob_bet"]),
            "book": float(r["market_prob"]),
            "edge_pp": float(r["model_edge_pp"]),
        })
    return out


def picks(board: pl.DataFrame, rule: dict) -> list[dict]:
    """Everything on this week's board the rule names.

    Reads the same pre-blend edge every money figure in this project is
    measured on, so a pick here means what it meant in the replay that found
    the rule.
    """
    if board is None or board.height == 0:
        return []
    if rule.get("kind") == "lay":
        return _lay_picks(board, rule)
    sel = board.filter(
        (pl.col("model_edge_pp") >= float(rule["min_edge_pp"]))
        & (pl.col("odds") >= float(rule["min_odds"]))
        & (pl.col("odds") < float(rule["max_odds"]))
    )
    out = []
    for r in sel.sort("model_edge_pp", descending=True).iter_rows(named=True):
        out.append({
            "rule": rule["name"], "player": r.get("player_name"),
            "team": r.get("team"), "game": r.get("game_label"),
            "odds": int(r["odds"]), "ours": float(r["prob_bet"]),
            "book": float(r["market_prob"]),
            "edge_pp": float(r["model_edge_pp"]),
        })
    return out


def load(path: Path | str = PICKS_PATH) -> pl.DataFrame:
    p = Path(path)
    if not p.exists():
        return pl.DataFrame(schema={c: pl.Utf8 for c in COLUMNS})
    return pl.read_csv(p, infer_schema_length=0)


def kickoffs(season: int, week: int) -> dict[str, "datetime"]:
    """When each game of this week starts, keyed by `game_id`.

    Eastern clock, like `kick_sort` and every launchd slot in this project.
    THE ONE READER OF KICKOFF TIMES, so that everything asking "has this
    begun?" asks it of the same numbers — `first_kickoff` is the minimum of
    this and `src.export.prediction_freeze` gates on it.

    Empty when the schedule cannot be read, which is the behavior every
    caller had before this existed: a guard that invents kickoff times is
    worse than one that never fires.
    """
    from datetime import datetime

    from src.utils.paths import get_path  # noqa: PLC0415

    try:
        s = pl.read_parquet(get_path("raw") / "schedules.parquet")
    except Exception:                                            # noqa: BLE001
        return {}
    want = {"gameday", "gametime", "game_id"}
    if not want <= set(s.columns):
        return {}
    d = s.filter((pl.col("season") == int(season))
                 & (pl.col("week") == int(week)))
    out: dict = {}
    for gid, day, clock in d.select(["game_id", "gameday",
                                     "gametime"]).iter_rows():
        if not (day and clock and gid):
            continue
        try:
            out[gid] = datetime.strptime(f"{str(day)[:10]} {str(clock)[:5]}",
                                         "%Y-%m-%d %H:%M")
        except ValueError:
            continue
    return out


def eastern_now():
    """Now on the Eastern clock, naive, to compare with `kickoffs`.

    Kickoffs are read as Eastern wall-clock times. Compared with a bare
    `datetime.now()` they were right only because this machine runs on
    Eastern time; on a UTC host every freeze would land four hours late.
    """
    from datetime import datetime
    from zoneinfo import ZoneInfo

    return datetime.now(ZoneInfo("America/New_York")).replace(tzinfo=None)


def first_kickoff(season: int, week: int):
    """When this week's earliest game starts, or None if it cannot be read."""
    times = kickoffs(season, week).values()
    return min(times) if times else None


def week_has_started(season: int, week: int, now=None) -> bool:
    """Whether this week's first game has kicked off.

    **A TRACKED PICK IS A FORWARD TEST AND THE CLOCK STARTS AT THE OPEN.**
    `week_rollover.sh` runs the shortlist unconditionally, which is right
    while it only ever runs Tuesday to Thursday. A forced rebuild on a Sunday
    morning breaks that assumption: on 2026-10-04 one wrote thirteen week-4
    picks at game-day prices into a set whose whole premise is the price you
    could have acted on days earlier. Every row was honest — before its own
    kickoff, none on the game already played — and still the wrong kind of
    row, with hours of lead time where the rest of the set has days.
    """
    from datetime import datetime

    kick = first_kickoff(season, week)
    if kick is None:
        # Unreadable schedule: record, which is the old behavior. A guard that
        # silently stops recording is worse than one that never fires.
        return False
    return (now or eastern_now()) >= kick


def _label(game_id: str) -> str:
    """`2026_05_TB_DAL` -> `TB @ DAL`, the form `game` is stored in."""
    bits = str(game_id or "").split("_")
    return f"{bits[-2]} @ {bits[-1]}" if len(bits) >= 2 else str(game_id or "")


def started_labels(season: int, week: int, now=None) -> set[str]:
    """`"AWAY @ HOME"` for every game this week that has kicked off."""
    from datetime import datetime

    at = now or eastern_now()
    return {_label(gid) for gid, kick in kickoffs(season, week).items()
            if at >= kick}


def migrate(path: Path | str = PICKS_PATH) -> bool:
    """Rewrite the file under the current `COLUMNS`, padding new cells empty.

    Returns whether anything changed. A copy of the old file is left beside
    it first: this is the only record of what the rules said before kickoff.
    """
    import shutil
    from datetime import datetime

    p = Path(path)
    if not p.exists():
        return False
    with p.open(newline="") as fh:
        rd = csv.DictReader(fh)
        header = list(rd.fieldnames or [])
        rows = list(rd)
    if header == list(COLUMNS):
        return False
    stray = [c for c in header if c not in COLUMNS]
    if stray:
        raise ValueError(f"{p} has columns COLUMNS does not: {stray}")
    shutil.copy2(p, p.with_name(
        f"{p.stem}.pre-migrate-{datetime.now():%Y%m%d_%H%M%S}{p.suffix}"))
    tmp = p.with_suffix(".csv.tmp")
    with tmp.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(COLUMNS))
        w.writeheader()
        for r in rows:
            w.writerow({c: r.get(c, "") for c in COLUMNS})
    tmp.replace(p)
    return True


def record(rows: list[dict], *, season: int, week: int, market: str,
           recorded_on: str, path: Path | str = PICKS_PATH,
           allow_late: bool = False, now=None) -> int:
    """Append this week's picks. Returns how many were new.

    Idempotent on (season, week, market, rule, player): re-running the
    shortlist twice in a week must not double a rule's record, and a record
    that can be inflated by re-running it is not a record.

    NOTHING IS RECORDED ONCE THE WEEK HAS KICKED OFF — see `week_has_started`.
    `allow_late=True` overrides it, for a backfill that knows what it is doing.

    EXCEPT ON THE OVER/UNDER MARKETS (`PER_GAME_MARKETS`), which are gated
    per game: a row is dropped only when its own game has kicked off, and the
    rest are kept with `recorded_at` saying when.
    """
    from datetime import datetime

    at = now or eastern_now()
    if rows and not allow_late and market in PER_GAME_MARKETS:
        gone = started_labels(season, week, at)
        late = [r for r in rows if (r.get("game") or "") in gone]
        if late:
            print(f"  tracked picks: {len(late)} {market} rows are for games "
                  f"already under way and were not recorded.",
                  file=sys.stderr)
        rows = [r for r in rows if (r.get("game") or "") not in gone]
    elif rows and not allow_late and week_has_started(season, week, at):
        print(f"  tracked picks: week {week} has already kicked off — "
              f"{len(rows)} not recorded. A pick found after the week starts "
              f"is not the forward test this file holds.", file=sys.stderr)
        return 0
    p = Path(path)
    migrate(p)
    existing = load(p)
    seen = set()
    if existing.height:
        for r in existing.iter_rows(named=True):
            seen.add((str(r["season"]), str(r["week"]), r["market"],
                      r["rule"], r["player"]))
    fresh = []
    for r in rows:
        key = (str(season), str(week), market, r["rule"], r["player"])
        if key in seen:
            continue
        seen.add(key)
        fresh.append({"recorded_on": recorded_on, "season": season,
                      "week": week, "market": market,
                      "recorded_at": at.isoformat(timespec="seconds"), **r})
    if not fresh:
        return 0
    p.parent.mkdir(parents=True, exist_ok=True)
    write_header = not p.exists()
    with p.open("a", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(COLUMNS))
        if write_header:
            w.writeheader()
        for r in fresh:
            w.writerow({c: r.get(c) for c in COLUMNS})
    return len(fresh)


def _implied(odds) -> float | None:
    if odds in (None, ""):
        return None
    o = float(odds)
    if o == 0:
        return None
    return (100.0 / (o + 100.0)) if o > 0 else (abs(o) / (abs(o) + 100.0))


def _played_weeks(season: int) -> set[int]:
    """Weeks of `season` whose play-by-play is on disk.

    The gate that decides whether grading is possible at all, and the one that
    would be easy to leave out. A week that has not been played carries a
    `target` of 0 on every candidate, so grading against it reads as every pick
    losing — which is not a bad week, it is no week. Play-by-play is what the
    labels are extracted from, so a week absent there cannot have an outcome.
    """
    from src.utils.paths import get_path

    path = get_path("raw") / "pbp.parquet"
    if not path.exists():
        return set()
    weeks = (pl.scan_parquet(path)
             .filter(pl.col("season") == season)
             .select("week").unique().collect())
    return {int(w) for w in weeks["week"].to_list() if w is not None}


def unfinished(season: int, week: int) -> tuple[set[str], set[str]]:
    """Games of this week with no final yet, keyed BOTH ways callers need.

    Returns `(game_ids, labels)`, a label being `"AWAY @ HOME"` — the form
    `tracked_picks.csv` writes into its `game` column, and the only handle a
    pick has on the fixture it was made about.

    **A WEEK IS NOT A GAME.** `_played_weeks` answers at week granularity,
    which on a Monday is true the moment Sunday ends: the week has
    play-by-play, so every Monday-night pick grades against a target of 0 —
    backs recorded as losses and fades as wins, on a game kicking off that
    evening. The three ATL at NO picks of week 4 were settled that way while
    the game was still hours off, and both rules' headline records moved in
    their own favor because of it.

    One schedule read and ONE definition of what has finished, because two
    callers deciding that separately is how the same week came to be graded
    two different ways. `week_history._unplayed_games` delegates here.
    """
    from src.utils.paths import get_path

    try:
        s = pl.read_parquet(get_path("raw") / "schedules.parquet")
    except Exception:                                            # noqa: BLE001
        # Unreadable schedule: nothing is known to be unfinished, which is the
        # behavior callers had before this existed. A guard that invents a set
        # of unplayed games would silently stop grading the season.
        return (set(), set())
    want = {"home_score", "away_score", "home_team", "away_team"}
    if not want <= set(s.columns):
        return (set(), set())
    d = s.filter((pl.col("season") == int(season))
                 & (pl.col("week") == int(week))
                 & (pl.col("home_score").is_null()
                    | pl.col("away_score").is_null()))
    ids = (set(d["game_id"].to_list()) if "game_id" in d.columns else set())
    labels = {f"{r[0]} @ {r[1]}"
              for r in d.select(["away_team", "home_team"]).iter_rows()}
    return (ids, labels)


def _outcomes(target_type: str) -> pl.DataFrame | None:
    """Did each candidate score, by season, week and normalized name.

    Read off the candidate matrix rather than re-derived from play-by-play:
    `target` there is the same column the model is trained against, so a pick
    is graded on exactly the event the model was asked to predict. Deriving a
    second definition here is how a rule comes to be scored on something
    adjacent to what it claimed.
    """
    from src.prediction.predict import _norm_name_expr
    from src.utils.paths import get_path

    path = get_path("processed", target_type) / "features.parquet"
    if not path.exists():
        return None
    df = (pl.scan_parquet(path)
          .select(["season", "week", "player_name", "target"])
          .collect())
    if df.height == 0:
        return None
    return (df.with_columns([
                pl.col("season").cast(pl.Int64), pl.col("week").cast(pl.Int64),
                _norm_name_expr("player_name").alias("player_name_norm"),
                pl.col("target").cast(pl.Int64).alias("scored")])
            .select(["season", "week", "player_name_norm", "scored"])
            .unique(subset=["season", "week", "player_name_norm"], keep="last"))


def _pnl(kind: str, took_prob: float, fair_prob: float | None,
         scored: int) -> float | None:
    """One pick's return, flat, in units of the thing staked.

    A back is the ordinary case: the price you took pays `(1 - q) / q` when it
    lands and costs the stake when it does not.

    A lay is scored the other way up, and at the de-vigged price rather than
    the posted one, because the posted price has no No side to take — the same
    convention `shortlist_backtest.fade_side` uses, win `1` and lose
    `p / (1 - p)` inverted. Two formulas for this would be two different claims
    wearing one name, so this defers to that one rather than restating it.
    """
    if scored is None:
        return None
    if kind == "lay":
        if fair_prob is None or not (0.0 < fair_prob < 1.0):
            return None
        return -(1.0 - fair_prob) / fair_prob if scored == 1 else 1.0
    if took_prob is None or not (0.0 < took_prob < 1.0):
        return None
    return (1.0 - took_prob) / took_prob if scored == 1 else -1.0


def score(target_type: str, path: Path | str = PICKS_PATH) -> dict | None:
    """What the tracked picks have done: closing-line value first, then results.

    CLV leads because it answers sooner. `graded` is only filled where the
    outcome is on disk, which for a live week is after the results land — a
    rule with picks and no grades yet is the normal state, not a fault.
    """
    from src.evaluation.betlog import _implied as implied_odds
    from src.evaluation.clv import line_movement

    rows = load(path).filter(pl.col("market") == target_type)
    if rows.height == 0:
        return None

    moves = line_movement(target_type)
    from src.prediction.predict import _norm_name_expr
    rows = rows.with_columns([
        pl.col("season").cast(pl.Int64), pl.col("week").cast(pl.Int64),
        pl.col("odds").cast(pl.Float64),
        _norm_name_expr("player").alias("player_name_norm"),
    ])
    clv_rows = []
    if moves is not None:
        closes = (moves.select(["season", "week", "player_name_norm",
                                pl.col("close_odds")])
                  .unique(subset=["season", "week", "player_name_norm"],
                          keep="last"))
        j = rows.join(closes, on=["season", "week", "player_name_norm"],
                      how="left")
        # Which way is good, per rule. A lay wants the Yes price to drift.
        sides = {r["name"]: (-1.0 if r.get("kind") == "lay" else 1.0)
                 for r in RULES}
        for r in j.iter_rows(named=True):
            took, close = implied_odds(r["odds"]), implied_odds(r.get("close_odds"))
            if took is None or close is None:
                continue
            clv_rows.append({"rule": r["rule"], "player": r["player"],
                             "clv_pp": (close - took) * 100
                                       * sides.get(r["rule"], 1.0)})

    # ── Results, where the week has actually been played ──────────────────
    graded_rows = []
    outcomes = _outcomes(target_type)
    if outcomes is not None:
        playable = {
            int(sn): _played_weeks(int(sn))
            for sn in rows["season"].unique().to_list() if sn is not None
        }
        # AND THEN PER GAME, because the week gate above is true from the
        # moment Sunday ends. Keyed on the `game` label the pick carries,
        # which is the only handle it has on its own fixture.
        pending = {
            (int(sn), int(wk)): unfinished(int(sn), int(wk))[1]
            for sn, wk in {(r[0], r[1]) for r in
                           rows.select(["season", "week"]).iter_rows()
                           if r[0] is not None and r[1] is not None}
        }
        g = rows.join(outcomes,
                      on=["season", "week", "player_name_norm"], how="left")
        kinds = {r["name"]: r.get("kind", "back") for r in RULES}
        for r in g.iter_rows(named=True):
            if int(r["week"]) not in playable.get(int(r["season"]), set()):
                continue
            if (r.get("game") or "") in pending.get(
                    (int(r["season"]), int(r["week"])), set()):
                continue
            if r.get("scored") is None:
                continue
            took = implied_odds(r["odds"])
            fair = r.get("book")
            v = _pnl(kinds.get(r["rule"], "back"), took,
                     float(fair) if fair is not None else None,
                     int(r["scored"]))
            if v is None:
                continue
            right = (int(r["scored"]) == 0 if kinds.get(r["rule"]) == "lay"
                     else int(r["scored"]) == 1)
            graded_rows.append({"rule": r["rule"], "pnl": v, "right": right,
                                "season": int(r["season"]),
                                "week": int(r["week"])})

    out = {}
    for rule in sorted(set(rows["rule"].to_list())):
        mine = [c for c in clv_rows if c["rule"] == rule]
        out[rule] = {
            "kind": next((r.get("kind", "back") for r in RULES
                          if r["name"] == rule), "back"),
            "picks": int(rows.filter(pl.col("rule") == rule).height),
            "weeks": int(rows.filter(pl.col("rule") == rule)
                         .select(["season", "week"]).unique().height),
            "clv_scored": len(mine),
            "mean_clv_pp": (sum(c["clv_pp"] for c in mine) / len(mine)
                            if mine else None),
            "beat_close_pct": (len([c for c in mine if c["clv_pp"] > 0]) / len(mine)
                               if mine else None),
        }
        # `graded` stays absent until a week has been played, which is the
        # honest shape: a rule with picks and no results yet is the normal
        # state for a live week, and an empty block would read as a verdict.
        done = [x for x in graded_rows if x["rule"] == rule]
        if done:
            out[rule]["graded"] = {
                "picks": len(done),
                "weeks": len({(x["season"], x["week"]) for x in done}),
                "landed_pct": len([x for x in done if x["right"]]) / len(done),
                "return_pct": 100.0 * sum(x["pnl"] for x in done) / len(done),
            }
    return {"target_type": target_type, "rules": out}
